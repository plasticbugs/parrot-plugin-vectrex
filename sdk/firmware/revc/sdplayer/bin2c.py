#!/usr/bin/env python3
"""bin2c.py in.bin name out.h -- a binary as a C array (the Game Boy kernel)."""
import sys
src, name, out = sys.argv[1:4]
d = open(src, "rb").read()
with open(out, "w") as f:
    f.write(f"// generated by bin2c.py from {src.rsplit('/', 1)[-1]}\n#pragma once\n#include <stdint.h>\n")
    f.write(f"#define {name.upper()}_LEN {len(d)}\n")
    f.write(f"static const uint8_t {name}[{len(d)}] = {{\n")
    for i in range(0, len(d), 16):
        f.write("  " + ",".join(f"0x{b:02x}" for b in d[i:i + 16]) + ",\n")
    f.write("};\n")
