def main():
    rows = {}
    for line in GLYPHS.split("\n"):
        if not line:
            continue
        ch, art = line[0], line[2:].split("|")
        assert len(art) == 8 and all(len(r) == 5 and set(r) <= set("#.") for r in art), line
        assert ch not in rows, ch
        rows[ch] = [sum(0x80 >> i for i, c in enumerate(r) if c == "#") for r in art]
    assert sorted(rows) == [chr(c) for c in range(32, 127)], "every character from space to ~"
    print("// cvfont.c -- see cvfont.h. Made by mkcvfont.py from the glyphs drawn there: edit those.")
    print('#include "cvfont.h"\n')
    print("const uint8_t cvfont[95][8] = {")
    for c in range(32, 127):
        name = {"\\": "backslash"}.get(chr(c), chr(c))
        print("    {%s},   // %s" % (", ".join("0x%02X" % v for v in rows[chr(c)]), name))
    print("};")
    print(r'''
void cvfont_char(canvas_t *c, int x, int y, int ch, uint8_t fg, uint8_t bg) {
    if (ch < 32 || ch > 126) ch = '?';
    const uint8_t *g = cvfont[ch - 32];
    for (int r = 0; r < CVFONT_H; r++) {
        const int py = y + r;
        if ((unsigned)py >= VDP_H) continue;
        for (int b = 0; b < CVFONT_W; b++) {
            const int px = x + b;
            const uint8_t colour = g[r] >> (7 - b) & 1 ? fg : bg;
            if ((unsigned)px >= VDP_W || c->px[py][px] == colour) continue;
            c->px[py][px] = colour;
            c->dirty[py >> 3][px >> 3] = 1;
        }
    }
}

void cvfont_line(canvas_t *c, int x, int y, int cols, const char *s, uint8_t fg, uint8_t bg) {
    for (int i = 0; i < cols; i++) {
        const int ch = s && *s ? (unsigned char)*s++ : ' ';
        cvfont_char(c, x + i * CVFONT_W, y, ch, fg, bg);
    }
}''')

main()
