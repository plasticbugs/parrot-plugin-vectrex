#!/usr/bin/env python3
"""mkpins.py out.h -- pins.h, the rev C pin order (hw3/pins.py), for
../sdplayer/perm.h (cvframes.c)."""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "..", "hw3"))
import pins as N

with open(sys.argv[1], "w") as f:
    f.write("// generated by sdk/mkpins.py from hw3/pins.py\n#pragma once\n")
    f.write("#ifndef __ASSEMBLER__                  // (cvplay/cvserve.S takes the GPIO_An below)\n#include <stdint.h>\n")
    f.write("// addr_line[g] = cartridge address line on GPIO g\n")
    f.write("static const uint8_t addr_line[15] = {%s};\n" % ",".join(map(str, N.ADDR_GPIO)))
    f.write("// data_bit[k] = console data bit carried by GPIO 16+k\n")
    f.write("static const uint8_t data_bit[8] = {%s};\n" % ",".join(map(str, N.DATA_GPIO)))
    f.write("#endif\n")
    f.write("// GPIO_An = the GPIO that carries address line An\n")
    for line in range(15):
        f.write(f"#define GPIO_A{line} {N.ADDR_GPIO.index(line)}\n")
